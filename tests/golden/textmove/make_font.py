def _glyph_name(ch):
    return "space" if ch == " " else f"uni{ord(ch):04X}"


def _draw(rows):
    """行の絵から TrueType のグリフ（長方形の輪郭の集まり）・送り幅・左端の x を作る"""
    pen = TTGlyphPen(None)
    width = max(len(r) for r in rows)
    xmin = None
    for r, row in enumerate(rows):
        top = (7 - r) * CELL           # 行 r の上端（基線は 0。行 6 が基線に乗る）
        bottom = top - CELL
        c = 0
        while c < len(row):
            if row[c] != "#":
                c += 1
                continue
            c0 = c
            while c < len(row) and row[c] == "#":
                c += 1
            x0, x1 = LSB + c0 * CELL, LSB + c * CELL
            xmin = x0 if xmin is None else min(xmin, x0)
            # 時計回り（y 上向き）: 左下 → 左上 → 右上 → 右下
            pen.moveTo((x0, bottom))
            pen.lineTo((x0, top))
            pen.lineTo((x1, top))
            pen.lineTo((x1, bottom))
            pen.closePath()
    return pen.glyph(), (width + 1) * CELL, (0 if xmin is None else xmin)


def build(path):
    order = [".notdef"] + [_glyph_name(ch) for ch in GLYPHS] + ["uni200C"]
    glyf = {}
    metrics = {}
    cmap = {}
    # .notdef は中抜きの箱（豆腐）
    pen = TTGlyphPen(None)
    for (x0, y0, x1, y1) in ((LSB, 0, LSB + 4 * CELL, 7 * CELL),):
        pen.moveTo((x0, y0)); pen.lineTo((x0, y1)); pen.lineTo((x1, y1)); pen.lineTo((x1, y0))
        pen.closePath()
        pen.moveTo((x0 + CELL, y0 + CELL)); pen.lineTo((x1 - CELL, y0 + CELL))
        pen.lineTo((x1 - CELL, y1 - CELL)); pen.lineTo((x0 + CELL, y1 - CELL))
        pen.closePath()
    glyf[".notdef"] = pen.glyph()
    metrics[".notdef"] = (5 * CELL, LSB)
    for ch, rows in GLYPHS.items():
        name = _glyph_name(ch)
        g, adv, xmin = _draw(rows)
        glyf[name] = g
        metrics[name] = (adv, xmin)
        cmap[ord(ch)] = name
    # U+200C（ゼロ幅非接合子）: 幅 0・絵なし（Stack Overflow の正規表現に入っている字）
    glyf["uni200C"] = TTGlyphPen(None).glyph()
    metrics["uni200C"] = (0, 0)
    cmap[0x200C] = "uni200C"

    fb = FontBuilder(UPEM, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyf)
    # lsb は輪郭の左端（空のグリフは 0）
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=ASCENT, descent=-DESCENT, lineGap=0)
    fb.setupNameTable({"familyName": "SVTM Block", "styleName": "Regular",
                       "uniqueFontIdentifier": "SVTM Block Regular 1.0",
                       "fullName": "SVTM Block Regular", "version": "Version 1.0",
                       "psName": "SVTMBlock-Regular",
                       "copyright": "scriptvedit test font (MIT)"})
    fb.setupOS2(sTypoAscender=ASCENT, sTypoDescender=-DESCENT, sTypoLineGap=0,
                usWinAscent=ASCENT, usWinDescent=DESCENT, achVendID="SVTM",
                fsType=0)
    fb.setupPost()
    fb.setupHead(unitsPerEm=UPEM, created=0, modified=0)   # 時刻を固定（決定的なバイト列）
    fb.save(path)


if __name__ == "__main__":
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "svtm_block.ttf")
    build(out)
    print(out)
