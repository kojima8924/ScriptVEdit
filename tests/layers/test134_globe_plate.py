from datetime import datetime, timezone

from scriptvedit import *

# globe(projection='plate'): 正距円筒の世界地図 ＋ night（2024-07-19 04:09 UTC の昼夜。
# 太陽の真下は北緯約 21 度・東経約 119 度）＋ 日付変更線をまたぐ弧（端で分けて描く）。
# 陸は手作りの模式の多角形。フォントもデータファイルも使わない。

LAND = [
    [(-10, 35), (40, 35), (60, 55), (140, 70), (150, 45), (120, 20), (100, 5),
     (75, 10), (50, 25), (30, 30), (0, 45)],
    [(-20, 30), (35, 30), (50, 10), (40, -35), (15, -35), (-15, 5)],
    [(-125, 50), (-60, 50), (-75, 20), (-100, 15), (-120, 30)],
    [(-80, 10), (-35, -5), (-60, -55), (-75, -20)],
    [(115, -15), (150, -12), (153, -38), (115, -35)],
]

g = globe(projection="plate", size=(640, 320), land=LAND, view=(0, 10))
g.night(datetime(2024, 7, 19, 4, 9, tzinfo=timezone.utc))
g.points([(35.7, 139.7), (37.8, -122.4), (51.5, -0.1)])
g.arc((35.7, 139.7), (37.8, -122.4), t=0.3, dur=1.2)    # 太平洋（日付変更線）を渡る
g.ripple((37.8, -122.4), t=1.5)
obj = g.build()
obj.time(3) <= move(x=0.5, y=0.5, anchor="center")
