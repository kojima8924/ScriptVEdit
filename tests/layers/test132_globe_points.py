from scriptvedit import *

# globe: 多角形の陸（手作りの模式図。実在の地図データではない）＋ 点き方 wave / staged。
# フォントもデータファイルも使わない（鍵は環境に依らない）。

# 模式の大陸（(経度, 緯度) の多角形。大まかな形だけ）
LAND = [
    [(-10, 35), (40, 35), (60, 55), (140, 70), (150, 45), (120, 20), (100, 5),
     (75, 10), (50, 25), (30, 30), (0, 45)],
    [(-20, 30), (35, 30), (50, 10), (40, -35), (15, -35), (-15, 5)],
    [(-125, 50), (-60, 50), (-75, 20), (-100, 15), (-120, 30)],
    [(-80, 10), (-35, -5), (-60, -55), (-75, -20)],
    [(115, -15), (150, -12), (153, -38), (115, -35)],
]

g = globe(size=480, land=LAND, view=(25, 60), step=2.0)
cities = [(35.7, 139.7), (51.5, -0.1), (1.35, 103.8), (-33.9, 18.4), (19.1, 72.9),
          (55.8, 37.6), (30.0, 31.2), (-23.5, -46.6), (40.7, -74.0)]
# 起点から近い順に 60 度/秒で点く（角度の距離 ÷ 速さ）
g.points(cities, t=0.2, appear=("wave", (30.0, 60.0), 60), color="fg")
# 1点 → 残り全部（件数は累積）
g.points([(48.9, 2.4), (52.5, 13.4), (41.9, 12.5), (59.3, 18.1), (39.9, 116.4)],
         t=0.5, appear=("staged", [(0.0, 1), (0.6, 5)]), color="muted", radius=3,
         name="sites")
obj = g.build(duration=2.5)
obj.time(3) <= move(x=0.5, y=0.5, anchor="center")
